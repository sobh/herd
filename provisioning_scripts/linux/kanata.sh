#!/bin/sh
# {{SCRIPT}}
#
# Description:
#   Provision the kanata keymapper: add the uinput group, add the user to the
#   input and uinput groups, and install a udev rule for /dev/uinput. Log in
#   again for the groups to apply. See:
#   https://github.com/jtroo/kanata/blob/main/docs/setup-linux.md
#
# Usage:
#   {{SCRIPT}} [-h]
#
# Options:
#   -h         Show this help message
#
# Requirements:
#   Linux with udev, doas or sudo, groupadd, and usermod
#
# Exit codes:
#   0  Success or help displayed
#   1  Invalid usage
#   2  No doas or sudo found

#---- Parameters ---------------------------------------------------------------
DOAS=""
getdoas() {
	command -v doas >/dev/null 2>&1 && {
		echo doas
		return 0
	}
	command -v sudo >/dev/null 2>&1 && {
		echo sudo
		return 0
	}
	echo unknown
	return 1
}

usage() {
	sed -n '2,/^$/s/^#[[:space:]]\{0,1\}//p' "$0" |
		sed "s/{{SCRIPT}}/$(basename "$0")/g"
}

#---- Main ---------------------------------------------------------------------

#---- Options --------------------------
while getopts ':h' opt; do
	case $opt in
	h)
		usage
		exit 0
		;;
	*)
		printf 'Unknown option: -%s\n' "$OPTARG" >&2
		usage >&2
		exit 1
		;;
	esac
done
shift "$((OPTIND - 1))"

if [ "$#" -gt 0 ]; then
	printf 'Expected no arguments\n' >&2
	usage >&2
	exit 1
fi

#---- Probe System ---------------------
SUPPORTED_DOAS="doas, sudo"
DOAS=$(getdoas)

if [ "$DOAS" = "unknown" ]; then
	echo "Unable to find a supported privilege escalation command. Not in ($SUPPORTED_DOAS)." >&2
	exit 2
fi

#---- Kanata ---------------------------
$DOAS groupadd -f uinput

$DOAS usermod -aG input "$USER"
$DOAS usermod -aG uinput "$USER"

cat <<EOF | $DOAS tee /etc/udev/rules.d/90-kanata.rules >/dev/null
# This file has been auto generated by the herd provisioning script: $0
KERNEL=="uinput", MODE="0660", GROUP="uinput", OPTIONS+="static_node=uinput"
EOF

$DOAS udevadm control --reload
$DOAS udevadm trigger --verbose --name-match=uinput
